import { mkdir, readFile, readdir } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { succeeded } from "../exec.js";
import {
  type CaptureRuntime,
  type CollectorOutcome,
  type Runtime,
  blockedOutcome,
  emptyOutcome,
} from "../runtime.js";
import {
  type ComponentDeclaration,
  type ComponentPlan,
  componentId,
} from "../types.js";
import { jsonText, sha256Text, toPosix, writeStaged } from "../util.js";

type ProductDecl = Extract<ComponentDeclaration, { kind: "product" }>;

const DEFAULT_DIR = fileURLToPath(
  new URL("../../../../third_party/code-to-prd/", import.meta.url),
);

export const codeToPrdDir = (rt: Runtime): string =>
  rt.ctx.env["REA_WEB_CODE_TO_PRD_DIR"] ?? DEFAULT_DIR;

interface Vendored {
  dir: string;
  analyzer: string;
  scaffolder: string;
  analyzerSha: string;
  scaffolderSha: string;
  revision: string | null;
  license: string;
}

async function loadVendored(
  rt: Runtime,
): Promise<Vendored | { error: string }> {
  const dir = codeToPrdDir(rt);
  try {
    const analyzer = join(dir, "scripts", "codebase_analyzer.py");
    const scaffolder = join(dir, "scripts", "prd_scaffolder.py");
    const [a, s, license, changes] = await Promise.all([
      readFile(analyzer, "utf8"),
      readFile(scaffolder, "utf8"),
      readFile(join(dir, "LICENSE"), "utf8"),
      readFile(join(dir, "DOWNSTREAM-CHANGES.md"), "utf8").catch(() => ""),
    ]);
    return {
      dir,
      analyzer,
      scaffolder,
      analyzerSha: sha256Text(a),
      scaffolderSha: sha256Text(s),
      revision: /\b([0-9a-f]{40})\b/u.exec(changes)?.[1] ?? null,
      license,
    };
  } catch (error) {
    return {
      error: `Code-to-PRD scripts not found at ${dir}: ${(error as NodeJS.ErrnoException).code ?? "unreadable"}`,
    };
  }
}

const pythonEnv = (): Record<string, string> => ({
  PATH: process.env["PATH"] ?? "/usr/bin:/bin",
  LC_ALL: "C.UTF-8",
  PYTHONIOENCODING: "utf-8",
  PYTHONDONTWRITEBYTECODE: "1",
});

export async function plan(
  decl: ProductDecl,
  rt: Runtime,
): Promise<ComponentPlan> {
  const py = await rt.run(["python3", "--version"], {
    env: pythonEnv(),
    timeoutMs: 15_000,
  });
  const vendored = await loadVendored(rt);
  const source = rt.build.components.find(
    (c) =>
      c.kind === "source" &&
      (c.id === decl.source_component_id ||
        componentId(c) === decl.source_component_id),
  );
  return {
    id: componentId(decl),
    kind: "product",
    collector: "code-to-prd",
    permissions: [
      {
        check: "python3 available",
        ok: succeeded(py),
        detail: succeeded(py)
          ? py.stdout.trim() || py.stderr.trim()
          : "python3 not found on the runner PATH",
      },
      {
        check: "vendored Code-to-PRD scripts",
        ok: !("error" in vendored),
        detail:
          "error" in vendored
            ? vendored.error
            : `scripts sha256 ${vendored.analyzerSha.slice(0, 12)}.../${vendored.scaffolderSha.slice(0, 12)}...`,
      },
      {
        check: `source component ${decl.source_component_id} declared`,
        ok: source !== undefined,
        detail:
          source === undefined
            ? "product documentation is generated from a declared source component"
            : "found",
      },
    ],
    estimated_bytes: null,
    dependencies: source === undefined ? [] : [componentId(source)],
    method: "Code-to-PRD static analysis (python3 -I, stdlib only)",
    omissions: [
      {
        what: "Exact-source guarantee",
        reason:
          "The PRD is generated by static, heuristic analysis. It is product documentation, not a backup of the source.",
        remediation:
          "Rely on the source component (git bundle) for exact source; treat the PRD as a navigational aid and review it.",
      },
    ],
    feasible: succeeded(py) && !("error" in vendored) && source !== undefined,
  };
}

const rewritePaths = (text: string, checkout: string): string =>
  text.split(`${checkout}/`).join("").split(checkout).join(".");

async function walkFiles(dir: string, prefix = ""): Promise<string[]> {
  const out: string[] = [];
  for (const e of (await readdir(dir, { withFileTypes: true })).sort((a, b) =>
    a.name < b.name ? -1 : 1,
  )) {
    const rel = prefix === "" ? e.name : `${prefix}/${e.name}`;
    if (e.isDirectory()) out.push(...(await walkFiles(join(dir, e.name), rel)));
    else if (e.isFile()) out.push(rel);
  }
  return out;
}

export async function capture(
  decl: ProductDecl,
  rt: CaptureRuntime,
): Promise<CollectorOutcome> {
  const cid = componentId(decl);
  const root = `product/${decl.id}/`;
  const base = {
    title: `Product documentation (${decl.id})`,
    method: "Code-to-PRD static analysis (python3 -I)",
    root,
  };
  const vendored = await loadVendored(rt);
  if ("error" in vendored)
    return blockedOutcome(base, {
      what: "Product documentation",
      reason: vendored.error,
      remediation:
        "Install the runner with third_party/code-to-prd, or set REA_WEB_CODE_TO_PRD_DIR to its location.",
    });
  const srcId = decl.source_component_id.startsWith("source:")
    ? decl.source_component_id.slice("source:".length)
    : decl.source_component_id;
  const co = await rt.checkout(srcId);
  if (!co.ok)
    return blockedOutcome(base, {
      what: "Product documentation",
      reason: co.reason,
      remediation: co.remediation,
    });
  const py = await rt.run(["python3", "--version"], {
    env: pythonEnv(),
    timeoutMs: 15_000,
  });
  if (!succeeded(py))
    return blockedOutcome(base, {
      what: "Product documentation",
      reason: "python3 is not available on the runner",
      remediation:
        "Install python3 (3.8 or newer) on the runner; Code-to-PRD uses only the standard library.",
    });

  const start = rt.now();
  const work = join(rt.ctx.workspace, `prd-${Date.now()}`);
  await mkdir(work, { recursive: true });
  const analysisPath = join(work, "analysis.json");
  const prdDir = join(work, "prd");
  const analyze = await rt.run(
    ["python3", "-I", vendored.analyzer, co.dir, "-o", analysisPath],
    { cwd: work, env: pythonEnv(), timeoutMs: 300_000 },
  );
  if (!succeeded(analyze))
    return blockedOutcome(base, {
      what: "Product documentation",
      reason: `codebase_analyzer.py failed: ${rt.failure(analyze)}`,
      remediation:
        "Inspect the source layout; the analyzer supports common web frameworks only.",
    });
  const scaffold = await rt.run(
    [
      "python3",
      "-I",
      vendored.scaffolder,
      analysisPath,
      "-o",
      prdDir,
      `--project-name=${decl.name}`,
    ],
    { cwd: work, env: pythonEnv(), timeoutMs: 300_000 },
  );
  if (!succeeded(scaffold))
    return blockedOutcome(base, {
      what: "Product documentation",
      reason: `prd_scaffolder.py failed: ${rt.failure(scaffold)}`,
      remediation: "Review analysis.json; the scaffolder rejected it.",
    });

  type Analysis = {
    summary?: Record<string, unknown>;
    project?: Record<string, unknown>;
  };
  let analysis: Analysis;
  try {
    analysis = JSON.parse(
      rewritePaths(await readFile(analysisPath, "utf8"), co.dir),
    ) as Analysis;
  } catch {
    return blockedOutcome(base, {
      what: "Product documentation",
      reason: "codebase_analyzer.py did not produce valid JSON",
      remediation: "Inspect the source layout and the analyzer output.",
    });
  }
  const stage = await rt.stageDir(cid);
  await writeStaged(
    stage,
    `${root}analysis.json`,
    jsonText(analysis, rt.ctx.redactor),
  );
  const prdFiles = await walkFiles(prdDir);
  for (const rel of prdFiles) {
    const text = rewritePaths(
      await readFile(join(prdDir, ...rel.split("/")), "utf8"),
      co.dir,
    );
    await writeStaged(
      stage,
      `${root}prd/${toPosix(rel)}`,
      rt.ctx.redactor.redactText(text),
    );
  }
  const summary: Record<string, unknown> = {
    ...analysis.summary,
    framework: analysis.project?.["framework"] ?? null,
    stack_type: analysis.project?.["stack_type"] ?? null,
  };
  const readme = [
    `# Product documentation: ${decl.name}`,
    "",
    "This directory is **product documentation generated by static analysis** of the captured source checkout. It is **not an exact-source backup**: it is a heuristic summary (routes, pages, endpoints, enums, models) that can miss or misreport behaviour. Neither a PRD nor decompiled output replaces the source component of this package.",
    "",
    "## What is here",
    "",
    "- `analysis.json`: output of Code-to-PRD `codebase_analyzer.py`, parsed and re-serialised as JSON. File paths are made relative to the source checkout root and the job's redactor is applied to string values; nothing else is changed.",
    "- `prd/`: Markdown scaffold produced by `prd_scaffolder.py` from that analysis. Sections marked TODO were not filled in automatically and need human review.",
    "",
    "## Real versus mock integrations",
    "",
    "The analyzer's `apis` section reports endpoints it classifies as integrated or mock (`integrated`, `mock_detected`). That classification is exactly what the analyzer reports; this package makes no independent determination of whether any integration is real or mocked at runtime.",
    "",
    "## Provenance",
    "",
    `- Tool: Code-to-PRD (MIT), pinned revision ${vendored.revision ?? "unknown"}.`,
    `- codebase_analyzer.py sha256: ${vendored.analyzerSha}`,
    `- prd_scaffolder.py sha256: ${vendored.scaffolderSha}`,
    `- Source component: ${co.sourceComponentId} at ${co.headSha}`,
    `- Generated at: ${start.toISOString()}`,
    ...(decl.rea_target_ids.length > 0
      ? [
          `- Linked REA targets (evidence not embedded here): ${decl.rea_target_ids.join(", ")}`,
        ]
      : []),
    "",
    "The tool ran as `python3 -I <script>` (Python standard library only) against a clean checkout rebuilt from this package's own source bundle, so git-ignored files such as `.env` were never visible to it.",
    "",
  ].join("\n");
  await writeStaged(stage, `${root}README.md`, readme);

  const outcome = emptyOutcome(base);
  return {
    ...outcome,
    status: "captured",
    limitations: [
      "Generated by static, heuristic analysis; not an exact-source backup and not a guarantee of completeness.",
      "Real-versus-mock integration status is only what the analyzer reports.",
    ],
    capturedAt: { start: start.toISOString(), end: rt.now().toISOString() },
    stageDir: stage,
    tools: ["python3"],
    relationships: [
      { from: cid, to: co.sourceComponentId, kind: "generated_from" },
    ],
    licenses: {
      path: "licenses/code-to-prd-MIT.txt",
      content: vendored.license,
      notice: `Code-to-PRD (MIT License, pinned revision ${vendored.revision ?? "unknown"}) generated the product documentation under ${root}. Its licence text is in licenses/code-to-prd-MIT.txt.`,
    },
    details: {
      generator: "Code-to-PRD",
      pinned_revision: vendored.revision,
      analyzer_sha256: vendored.analyzerSha,
      scaffolder_sha256: vendored.scaffolderSha,
      python_version: py.stdout.trim() || py.stderr.trim(),
      source_component: co.sourceComponentId,
      source_head_sha: co.headSha,
      analysis_summary: summary,
      prd_files: prdFiles.length,
      rea_target_ids: decl.rea_target_ids,
      exact_source_backup: false,
    },
  };
}
