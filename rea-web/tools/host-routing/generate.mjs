#!/usr/bin/env node
// Generate docs/HOST-ROUTING.md: for every target class in the routing table
// (packages/contracts ROUTE_TABLE), what a runner must offer, and whether each
// probed host offers it, read from that host's live binary_session
// tool_availability. Hosts that were not probed are listed as not probed;
// nothing is inferred for them.
//
// Usage: node tools/host-routing/generate.mjs [--probe <file>]... [--out <file>]

import { readFileSync, writeFileSync } from "node:fs";
import { basename, resolve } from "node:path";
import { gunzipSync } from "node:zlib";
import { ROUTE_TABLE } from "@rea-web/contracts";

const args = process.argv.slice(2);
const probes = [];
let out = resolve("docs/HOST-ROUTING.md");
for (let i = 0; i < args.length; i += 2) {
  if (args[i] === "--probe") probes.push(resolve(args[i + 1]));
  else if (args[i] === "--out") out = resolve(args[i + 1]);
}
if (probes.length === 0)
  probes.push(
    resolve("tools/parity-matrix/probes/linux-x64-node22-no-providers.json.gz"),
  );

const readJson = (p) =>
  JSON.parse(
    p.endsWith(".gz")
      ? gunzipSync(readFileSync(p)).toString("utf8")
      : readFileSync(p, "utf8"),
  );

/** Per probed host: tool -> { available, reason, remediation }. */
const hosts = probes.map((path) => {
  const probe = readJson(path);
  const result = probe.binary_session?.structuredContent?.result;
  const groups = result?.tool_availability?.groups;
  if (!Array.isArray(groups))
    throw new Error(`${path}: no tool_availability groups`);
  const tools = new Map();
  for (const g of groups)
    for (const name of g.names)
      tools.set(name, {
        available: g.available === true,
        reason: g.reason ?? null,
        remediation: g.remediation ?? null,
      });
  const providers = (result.analysis_provider_candidates ?? [])
    .filter((c) => c.available === true || c.status === "available")
    .map((c) => c.provider ?? c.name)
    .filter(Boolean);
  return {
    label: basename(path).replace(/\.json(\.gz)?$/u, ""),
    tools,
    providers,
  };
});

const cell = (host, route) => {
  if (route.first_tool === null) return "no route";
  const missing = route.required_tools.filter((t) => !host.tools.has(t));
  if (missing.length) return `not advertised: ${missing.join(", ")}`;
  const statuses = route.required_tools.map((t) => [t, host.tools.get(t)]);
  const blocked = statuses.filter(
    ([, s]) => !s.available && s.reason !== "target_required",
  );
  if (blocked.length)
    return `unavailable: ${blocked.map(([t, s]) => `${t} (${s.reason})`).join("; ")}`;
  const needsTarget = statuses.some(
    ([, s]) => !s.available && s.reason === "target_required",
  );
  const providerNote =
    route.required_providers_any_of.length === 0
      ? ""
      : host.providers.some((p) => route.required_providers_any_of.includes(p))
        ? ""
        : ` · provider needed: one of ${route.required_providers_any_of.join(", ")} (none available)`;
  return `${needsTarget ? "available once a target is open" : "available"}${providerNote}`;
};

const lines = [
  "# Host routing matrix",
  "",
  "Generated by `tools/host-routing/generate.mjs` from the routing table in",
  "`packages/contracts/src/routing.ts` and live `binary_session` availability",
  "probes. Do not edit by hand. A host column reflects only what its probe",
  "observed; hosts without a probe are not claimed to support anything.",
  "",
  `Probed hosts: ${hosts.map((h) => `\`${h.label}\``).join(", ")}.`,
  "Not probed: macOS, Windows, hosts with Ghidra/Hopper/IDA/JADX/Binwalk/Unblob/WABT/Chromium/ADB installed.",
  "",
  `| Target class | First tool | Required tools | Providers (any of) | OS | ${hosts.map((h) => h.label).join(" | ")} |`,
  `| --- | --- | --- | --- | --- | ${hosts.map(() => "---").join(" | ")} |`,
];
for (const route of ROUTE_TABLE)
  lines.push(
    `| \`${route.class}\` | ${route.first_tool ? `\`${route.first_tool}\`` : "—"} | ${route.required_tools.map((t) => `\`${t}\``).join(", ") || "—"} | ${route.required_providers_any_of.join(", ") || "—"} | ${route.required_os.join(", ") || "any"} | ${hosts.map((h) => cell(h, route)).join(" | ")} |`,
  );
lines.push(
  "",
  "## Routing a target to a host",
  "",
  "Jobs carry the route's required tools and OS as requirements. A runner",
  "claims a job only when its live capability report satisfies them",
  "(`unmetRequirements` in `packages/contracts/src/runner.ts`), and the",
  "routing view of a target lists every runner with its unmet requirements",
  "and upstream's remediation. Runner-local targets are always pinned to the",
  "runner that registered them. To cover a class that is unavailable on the",
  "cloud runner, run a companion runner on a host that has the provider",
  "(see `docs/COMPANION-RUNNER.md`) and probe it with",
  "`node tools/parity-matrix/probe.mjs` to add a column here.",
  "",
);
writeFileSync(out, `${lines.join("\n")}`);
console.log(
  `wrote ${out} (${ROUTE_TABLE.length} classes, ${hosts.length} host(s))`,
);
